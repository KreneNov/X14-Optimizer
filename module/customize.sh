#!/system/bin/sh
# customize.sh - KernelSU Module Installer (POSIX sh)

SKIPUNZIP=0

DEVICE=$(getprop ro.product.device)
MODEL=$(getprop ro.product.model)
SOC=$(getprop ro.board.platform)

ui_print "=========================================="
ui_print "  Xiaomi 14 Perf & Battery Optimizer"
ui_print "  Version: v1.3.0"
ui_print "=========================================="
ui_print "- Device : ${DEVICE:-unknown} (${MODEL:-unknown})"
ui_print "- Board  : ${SOC:-unknown}"

if [ "$DEVICE" = "houji" ]; then
    ui_print "- Profile: Xiaomi 14 (houji) native support"
else
    ui_print "- Profile: Generic fallback mode (graceful sysfs detection)"
fi

CONFIG_DIR="/data/adb/x14_perf_battery"
CONFIG_FILE="$CONFIG_DIR/config.conf"
GAMES_FILE="$CONFIG_DIR/games.list"

mkdir -p "$CONFIG_DIR"
chmod 0755 "$CONFIG_DIR"

if [ -e /sys/class/power_supply/battery/constant_charge_current ]; then
    DEF_CHARGE_MODE="fcc"
else
    DEF_CHARGE_MODE="suspend"
fi

if [ ! -f "$CONFIG_FILE" ]; then
    ui_print "- Creating default configuration at $CONFIG_FILE"
    cat <<EOF > "$CONFIG_FILE"
PROFILE=balanced
CHARGE_ENABLED=1
CHARGE_STOP_PCT=85
CHARGE_RESUME_PCT=75
CHARGE_LIMIT_MA=0
CHARGE_MODE=$DEF_CHARGE_MODE
FPS_MODE=smart120
FPS_PK_MODE=none
SCREEN_OFF_ENABLED=1
SCREEN_OFF_DEBOUNCE=30
SCREEN_OFF_DOZE=0
THERMAL_GUARD_ENABLED=1
THERMAL_WARN_C=42
THERMAL_CRIT_C=45
AUTO_GAME_ENABLED=1
JOYOSE_DISABLED=0
ZRAM_ENABLED=1
ZRAM_SIZE_GB=6
ZRAM_ALGO=lz4
GAME_AUTO_BYPASS=1
GAME_BYPASS_MIN_PCT=20
EOF
else
    ui_print "- Preserving existing configuration at $CONFIG_FILE"
    if [ "$DEVICE" = "houji" ] && grep -q '^CHARGE_MODE=suspend$' "$CONFIG_FILE" 2>/dev/null; then
        ui_print "- Migrating CHARGE_MODE: suspend -> fcc (True Bypass)"
        sed 's/^CHARGE_MODE=suspend$/CHARGE_MODE=fcc/' "$CONFIG_FILE" > "${CONFIG_FILE}.tmp"
        mv -f "${CONFIG_FILE}.tmp" "$CONFIG_FILE"
    fi
    if ! grep -q '^AUTO_GAME_ENABLED=' "$CONFIG_FILE" 2>/dev/null; then
        printf 'AUTO_GAME_ENABLED=1\n' >> "$CONFIG_FILE"
    fi
    if ! grep -q '^JOYOSE_DISABLED=' "$CONFIG_FILE" 2>/dev/null; then
        printf 'JOYOSE_DISABLED=0\n' >> "$CONFIG_FILE"
    fi
    if ! grep -q '^ZRAM_ENABLED=' "$CONFIG_FILE" 2>/dev/null; then
        printf 'ZRAM_ENABLED=1\n' >> "$CONFIG_FILE"
    fi
    if ! grep -q '^ZRAM_SIZE_GB=' "$CONFIG_FILE" 2>/dev/null; then
        printf 'ZRAM_SIZE_GB=6\n' >> "$CONFIG_FILE"
    fi
    if ! grep -q '^ZRAM_ALGO=' "$CONFIG_FILE" 2>/dev/null; then
        printf 'ZRAM_ALGO=lz4\n' >> "$CONFIG_FILE"
    fi
    if ! grep -q '^GAME_AUTO_BYPASS=' "$CONFIG_FILE" 2>/dev/null; then
        printf 'GAME_AUTO_BYPASS=1\n' >> "$CONFIG_FILE"
    fi
    if ! grep -q '^GAME_BYPASS_MIN_PCT=' "$CONFIG_FILE" 2>/dev/null; then
        printf 'GAME_BYPASS_MIN_PCT=20\n' >> "$CONFIG_FILE"
    fi
fi
chmod 0644 "$CONFIG_FILE"

if [ ! -f "$GAMES_FILE" ]; then
    ui_print "- Creating default Auto Game Mode list at $GAMES_FILE"
    cat <<EOF > "$GAMES_FILE"
com.garena.game.kgvn|max120
com.garena.game.kgvo|max120
com.vng.pubgmobile|max120
com.tencent.ig|max120
com.dts.freefiremax|max120
com.kurogame.wutheringwaves|cool60
EOF
else
    ui_print "- Preserving existing game list at $GAMES_FILE"
fi
chmod 0644 "$GAMES_FILE"

rm -f /data/local/tmp/x14_hw_cache.conf 2>/dev/null

# Clean up legacy system/vendor overlay if upgrading from v1.1.0
rm -rf "$MODPATH/system/vendor" 2>/dev/null

ui_print "- Setting file permissions..."
set_perm_recursive "$MODPATH" 0 0 0755 0644
set_perm_recursive "$MODPATH/bin" 0 0 0755 0755

for f in post-fs-data.sh service.sh action.sh uninstall.sh; do
    if [ -f "$MODPATH/$f" ]; then
        set_perm "$MODPATH/$f" 0 0 0755
    fi
done

# Prepare patched display thermal FPS XML for mount --bind in post-fs-data.sh
SRC_XML="/vendor/etc/display/thermallevel_to_fps.xml"
DEST_DIR="$MODPATH/files"
DEST_XML="$DEST_DIR/thermallevel_to_fps.xml"
if { [ "$DEVICE" = "houji" ] || [ -f "$SRC_XML" ]; } && [ -f "$SRC_XML" ] && grep -q '<ThermalLevelToFPSMap>' "$SRC_XML" 2>/dev/null && grep -q '</ThermalLevelToFPSMap>' "$SRC_XML" 2>/dev/null; then
    ui_print "- Preparing display thermal FPS bind-mount XML..."
    mkdir -p "$DEST_DIR"
    cat << 'EOF' > "$DEST_XML"
<?xml version="1.0" ?>
<!--
Generated by x14_perf_battery (houji) - Prevents 90Hz throttling at thermal levels 5-7.
Emergency 60Hz throttling at levels 8-10 is preserved.
-->
<ThermalLevelToFPSMap>
    <DeviceSettingList>
        <DefaultDevice version="1"/>
        <Device version="1">
            <ThermalLevelMap level="1" fps="144"/>
            <ThermalLevelMap level="2" fps="144"/>
            <ThermalLevelMap level="3" fps="120"/>
            <ThermalLevelMap level="4" fps="120"/>
            <ThermalLevelMap level="5" fps="120"/>
            <ThermalLevelMap level="6" fps="120"/>
            <ThermalLevelMap level="7" fps="120"/>
            <ThermalLevelMap level="8" fps="60"/>
            <ThermalLevelMap level="9" fps="60"/>
            <ThermalLevelMap level="10" fps="60"/>
        </Device>
    </DeviceSettingList>
</ThermalLevelToFPSMap>
EOF
    if [ -s "$DEST_XML" ] && grep -q '<ThermalLevelToFPSMap>' "$DEST_XML" && grep -q '</ThermalLevelToFPSMap>' "$DEST_XML" && grep -q '</Device>' "$DEST_XML" && grep -q '</DeviceSettingList>' "$DEST_XML" && grep -q 'level="5" fps="120"' "$DEST_XML" && grep -q 'level="6" fps="120"' "$DEST_XML" && grep -q 'level="7" fps="120"' "$DEST_XML"; then
        REF_CTX=$(stat -c %C "$SRC_XML" 2>/dev/null)
        case "$REF_CTX" in
            u:object_r:*) ;;
            *) REF_CTX="u:object_r:vendor_configs_file:s0" ;;
        esac
        chmod 0755 "$DEST_DIR" 2>/dev/null
        set_perm "$DEST_XML" 0 0 0644 "$REF_CTX"
        chcon --reference="$SRC_XML" "$DEST_XML" 2>/dev/null || chcon "$REF_CTX" "$DEST_XML" 2>/dev/null
        ui_print "- Patched XML ready at files/thermallevel_to_fps.xml ($REF_CTX)"
    else
        ui_print "- [WARN] Overlay XML validation failed, removing patched XML"
        rm -f "$DEST_XML"
    fi
else
    ui_print "- Skipping display thermal FPS XML (device/XML not matched)"
fi

ui_print "- Log file: /data/local/tmp/x14_perf_battery.log"
ui_print "- Installation complete. Reboot to activate."
